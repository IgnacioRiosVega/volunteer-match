// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest'
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { App } from '../src/App'
import { LocalStorageCatalogRepository } from '../src/data/repository'

function open(page: string) {
  window.history.replaceState(null, '', '/#/' + page)
  return render(<App />)
}

beforeEach(() => { window.localStorage.clear() })
afterEach(() => { cleanup(); vi.useRealTimers() })

describe('Aplicación web', () => {
  it('genera la matriz, explica bloqueos, calcula la solución y muestra la cobertura de los proyectos', async () => {
    const user = userEvent.setup()
    open('inicio')
    await user.click(within(screen.getByRole('region', { name: 'El talento correcto. Donde más importa.' })).getByRole('link', { name: 'Asignar voluntariado' }))
    await user.click(await screen.findByRole('button', { name: 'Generar matriz' }))
    const matrix = screen.getByRole('region', { name: 'Matriz de compatibilidad' })
    const details = screen.getByRole('complementary', { name: 'Detalle del cruce seleccionado' })
    await user.click(within(matrix).getByRole('button', { name: 'Amalia Ferral · Alfabetización digital (Puentes Digitales) · 100 puntos' }))
    expect(details).toHaveTextContent('Habilidades (45 %)')
    expect(details).toHaveTextContent('Flexibilidad (15 %)15 pts')
    expect(details).toHaveTextContent('Ubicación (10 %)10 pts')
    await user.keyboard('{ArrowLeft}')
    expect(details).toHaveTextContent('Educación ambiental')
    expect(within(matrix).getByRole('button', { pressed: true })).toHaveFocus()
    await user.click(within(matrix).getByRole('button', { name: 'Julia Belver · Mentoría en accesibilidad (Puentes Digitales) · Prohibido' }))
    expect(details).toHaveTextContent('Faltan habilidades obligatorias')
    expect(details).toHaveTextContent('se exige un mínimo de 4')

    await user.click(screen.getByRole('button', { name: 'Ejecutar algoritmo' }))
    expect(screen.getByRole('heading', { name: 'Asignación calculada' })).toBeInTheDocument()
    expect(screen.getByText(/11 pares reales · 1[.\u00a0]?080,83 puntos/)).toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: 'Ver resultados' }))
    const matches = await screen.findByRole('table', { name: 'Asignaciones óptimas' })
    expect(within(matches).getAllByRole('row')).toHaveLength(12)
    expect(within(matches).getByRole('rowheader', { name: /Amalia Ferral/ }).closest('tr')).toHaveTextContent('Alfabetización digital')
    expect(screen.getByRole('row', { name: /Mentoría en accesibilidad Puentes Digitales Sin candidatos elegibles/ })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Cobertura por proyecto' })).toBeInTheDocument()
    expect(screen.queryByText('Solución óptima frente al método voraz')).not.toBeInTheDocument()
    expect(screen.getByText('2 de 3 puestos cubiertos')).toBeInTheDocument()
    const focusProject = screen.getByRole('button', { name: /Puentes Digitales 2 de 3 puestos cubiertos/ })
    await user.click(focusProject)
    expect(focusProject).toHaveAttribute('aria-pressed', 'true')
    expect(within(matches).getAllByRole('row')).toHaveLength(3)
    await user.selectOptions(screen.getByRole('combobox', { name: 'ODS' }), '13')
    expect(within(matches).getAllByRole('row')).toHaveLength(3)
    expect(within(matches).getByRole('rowheader', { name: /Bruno Quisbert/ })).toBeInTheDocument()
    expect(screen.getByText('No hay vacantes sin candidatos elegibles en esta vista.')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Limpiar filtros' }))
    expect(within(matches).getAllByRole('row')).toHaveLength(12)
  })

  it('invalida la matriz si cambian los pesos y valida su suma', async () => {
    const user = userEvent.setup()
    open('simulador')
    await user.click(screen.getByRole('button', { name: 'Generar matriz' }))
    expect(screen.getByRole('button', { name: 'Ejecutar algoritmo' })).toBeInTheDocument()
    const input = screen.getByRole('spinbutton', { name: 'Habilidades' })
    await user.clear(input)
    await user.type(input, '55')
    expect(screen.queryByRole('button', { name: 'Ejecutar algoritmo' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Generar matriz' }))
    expect(screen.getByRole('alert')).toHaveTextContent('sumar 100 %')
  })

  it('navega por la guía, avanza en reproducción automática y reinicia', () => {
    vi.useFakeTimers()
    open('aprende')
    const navigation = screen.getByRole('navigation', { name: 'Navegación principal' })
    expect(within(navigation).getByRole('link', { name: 'Marco teórico' })).toHaveAttribute('href', '#/teoria')
    expect(within(navigation).getByRole('link', { name: 'Conclusiones' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Algoritmo de asignación' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Matriz original' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Resolver automáticamente' }))
    act(() => vi.advanceTimersByTime(1000))
    expect(screen.getByRole('heading', { name: 'Conversión de beneficios a costos' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Pausar' }))
    for (let step = 1; step < 8; step++) fireEvent.click(screen.getByRole('button', { name: 'Siguiente paso' }))
    expect(screen.getByRole('heading', { name: 'Resultado óptimo' })).toBeInTheDocument()
    expect(within(screen.getByRole('region', { name: 'Visualización paso a paso' })).getByText(/250 puntos/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Paso anterior' }))
    expect(screen.getByRole('heading', { name: /Ceros independientes en la matriz final/ })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Reiniciar' }))
    expect(screen.getByRole('button', { name: 'Paso anterior' })).toBeDisabled()
  })

  it('registra, consulta, edita y elimina un perfil con persistencia tras recargar', async () => {
    const user = userEvent.setup()
    const first = open('voluntarios')
    await user.click(screen.getByRole('button', { name: 'Nuevo voluntario' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre completo' }), 'Alina de Prueba')
    const skills = screen.getByRole('combobox', { name: 'Habilidades' })
    await user.type(skills, 'Lectu')
    await user.click(screen.getByRole('option', { name: /^Lectura / }))
    await user.type(skills, 'Mediación intercultural')
    await user.keyboard('{Enter}')
    await user.click(screen.getByRole('checkbox', { name: 'Lunes Mañana 08:00–12:00' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(screen.getByRole('status')).toHaveTextContent('Voluntario registrado.')
    await user.click(within(screen.getByRole('navigation', { name: 'Navegación principal' })).getByRole('link', { name: 'Inicio' }))
    const counts = await screen.findByRole('region', { name: 'Resumen del catálogo' })
    expect(within(counts).getByText('17', { exact: true })).toBeInTheDocument()
    first.unmount()

    open('voluntarios')
    await user.click(screen.getByRole('button', { name: 'Ver perfil de Alina de Prueba' }))
    expect(screen.getByRole('region', { name: 'Perfil de Alina de Prueba' })).toHaveTextContent('Lunes · 08:00–12:00')
    await user.click(screen.getByRole('button', { name: 'Editar a Alina de Prueba' }))
    const name = screen.getByRole('textbox', { name: 'Nombre completo' })
    await user.clear(name)
    await user.type(name, 'Alina Editada')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await user.click(screen.getByRole('button', { name: 'Eliminar a Alina Editada' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación' }))
    expect(screen.queryByRole('rowheader', { name: /Alina Editada/ })).not.toBeInTheDocument()
    expect(new LocalStorageCatalogRepository().load().catalog.volunteers).toHaveLength(16)
    await user.click(screen.getByRole('button', { name: 'Nuevo voluntario' }))
    await user.type(screen.getByRole('combobox', { name: 'Habilidades' }), 'mediac')
    expect(screen.getByRole('option', { name: /^Mediación intercultural / })).toBeInTheDocument()
  })

  it('crea y edita proyectos y puestos, y elimina puestos asociados con su proyecto', async () => {
    const user = userEvent.setup()
    open('proyectos')
    await user.click(screen.getByRole('button', { name: 'Nuevo proyecto' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre del proyecto' }), 'Taller de prueba')
    await user.type(screen.getByRole('combobox', { name: 'Organización del proyecto' }), 'UNICEF')
    await user.type(screen.getByRole('textbox', { name: 'Ubicación referencial' }), 'La Paz')
    await user.type(screen.getByRole('textbox', { name: 'Descripción' }), 'Escenario de práctica.')
    await user.click(screen.getByRole('checkbox', { name: 'ODS 4 · Educación de calidad' }))
    await user.click(screen.getByRole('checkbox', { name: 'ODS 10 · Reducción de las desigualdades' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await user.click(screen.getByRole('button', { name: 'Añadir puesto a Taller de prueba' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre del puesto' }), 'Tutoría de prueba')
    await user.click(screen.getByRole('checkbox', { name: 'Lunes Mañana 08:00–12:00' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await user.click(screen.getByText('Tutoría de prueba'))
    await user.click(screen.getByRole('button', { name: 'Editar puesto Tutoría de prueba' }))
    await user.click(screen.getByRole('checkbox', { name: 'Puesto abierto a asignación' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await user.click(screen.getByRole('button', { name: 'Editar proyecto Taller de prueba' }))
    const projectName = screen.getByRole('textbox', { name: 'Nombre del proyecto' })
    await user.clear(projectName)
    await user.type(projectName, 'Taller editado')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))

    const repository = new LocalStorageCatalogRepository()
    await user.click(within(screen.getByRole('navigation', { name: 'Navegación principal' })).getByRole('link', { name: 'Inicio' }))
    const summary = await screen.findByRole('region', { name: 'Resumen del catálogo' })
    expect(within(summary).getByText('6', { exact: true })).toBeInTheDocument()
    expect(within(summary).getByText('12', { exact: true })).toBeInTheDocument()
    expect(screen.getByRole('table', { name: 'Últimos proyectos registrados' })).toHaveTextContent('Taller editado')
    await user.click(within(screen.getByRole('navigation', { name: 'Navegación principal' })).getByRole('link', { name: 'Proyectos' }))
    expect(repository.load().catalog.projects.find(project => project.name === 'Taller editado'))
      .toMatchObject({ sdgs: [4, 10], organization: 'UNICEF' })
    expect(repository.load().catalog.projects.find(project => project.name === 'Taller editado')?.positions)
      .toMatchObject([{ name: 'Tutoría de prueba', active: false }])
    await user.click(screen.getByRole('button', { name: 'Eliminar proyecto Taller editado' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación' }))
    expect(repository.load().catalog.projects).toHaveLength(5)
  })

  it('pide confirmación antes de restaurar los datos de demostración', async () => {
    const user = userEvent.setup()
    const repository = new LocalStorageCatalogRepository()
    repository.save({ volunteers: [], projects: [] })
    open('simulador')
    await user.click(screen.getByRole('button', { name: 'Restaurar demostración' }))
    expect(repository.load().catalog.volunteers).toHaveLength(0)
    await user.click(screen.getByRole('button', { name: 'Restaurar datos' }))
    expect(screen.getByText('16 de 16 seleccionados')).toBeInTheDocument()
    expect(repository.load().catalog.projects).toHaveLength(5)
  })
})

describe('Archivos de asignación', () => {
  it('guarda, limpia y restaura un resultado en una sesión con otro catálogo', async () => {
    const user = userEvent.setup()
    const show = vi.fn(function (this: HTMLDialogElement) { this.open = true })
    const prototype = HTMLDialogElement.prototype
    const showDescriptor = Object.getOwnPropertyDescriptor(prototype, 'showModal')
    const closeDescriptor = Object.getOwnPropertyDescriptor(prototype, 'close')
    Object.defineProperty(prototype, 'showModal', { configurable: true, value: show })
    Object.defineProperty(prototype, 'close', { configurable: true, value: function (this: HTMLDialogElement) { this.open = false } })
    const file = vi.fn((_blob: Blob) => 'blob:assignment-test')
    vi.stubGlobal('URL', class extends URL {
      static createObjectURL = file
      static revokeObjectURL = vi.fn()
    })
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    try {
      const session = open('asignacion')
      await user.click(screen.getByRole('button', { name: 'Help' }))
      expect(screen.getByRole('dialog', { name: 'Guía del sistema de asignación' })).toHaveTextContent('Los cinco pesos deben sumar 100 %')
      await user.click(screen.getByRole('button', { name: 'Cerrar' }))
      await user.click(screen.getByRole('button', { name: 'Generar matriz' }))
      await user.click(screen.getByRole('button', { name: 'Ejecutar algoritmo' }))
      await user.click(screen.getByRole('link', { name: 'Ver resultados' }))
      const original = (await screen.findByRole('table', { name: 'Asignaciones óptimas' })).textContent
      await user.click(screen.getByRole('button', { name: 'Guardar' }))
      const dialog = screen.getByRole('dialog', { name: 'Guardar asignación' })
      const name = within(dialog).getByRole('textbox', { name: /Nombre del archivo/ })
      await user.clear(name)
      await user.type(name, 'Mi equipo.json')
      await user.click(within(dialog).getByRole('button', { name: 'Guardar JSON' }))
      expect((click.mock.contexts.at(-1) as HTMLAnchorElement | undefined)?.download).toBe('Mi equipo.json')
      const raw = await new Promise<string>((resolve, reject) => {
        const reader = new FileReader()
        reader.onload = () => resolve(String(reader.result))
        reader.onerror = reject
        reader.readAsText(file.mock.calls[0][0])
      })
      await user.click(screen.getByRole('link', { name: 'Volver a la asignación' }))
      await user.click(await screen.findByRole('button', { name: 'Limpiar' }))
      expect(screen.queryByRole('heading', { name: 'Matriz de compatibilidad' })).not.toBeInTheDocument()
      expect(screen.queryByRole('heading', { name: 'Asignación calculada' })).not.toBeInTheDocument()
      expect(screen.queryAllByRole('checkbox', { checked: true })).toHaveLength(0)
      await user.click(screen.getByRole('link', { name: 'Resultados' }))
      expect(await screen.findByText('Todavía no hay una asignación')).toBeInTheDocument()
      expect(screen.getByRole('button', { name: 'Abrir' })).toBeEnabled()
      session.unmount()

      const catalog = JSON.stringify({ volunteers: [], projects: [] })
      window.localStorage.setItem(LocalStorageCatalogRepository.key, catalog)
      open('resultados')
      const picker = await screen.findByLabelText('Archivo de asignación')
      const saved = new File([raw], 'Mi equipo.json', { type: 'application/json' })
      Object.defineProperty(saved, 'text', { value: async () => raw })
      await user.upload(picker, saved)
      expect((await screen.findByRole('table', { name: 'Asignaciones óptimas' })).textContent).toBe(original)
      expect(window.localStorage.getItem(LocalStorageCatalogRepository.key)).toBe(catalog)

      const bad = new File(['{}'], 'otro.json', { type: 'application/json' })
      Object.defineProperty(bad, 'text', { value: async () => '{}' })
      await user.upload(picker, bad)
      expect(await screen.findByRole('alert')).toHaveTextContent('incompatible')
      expect(screen.getByRole('table', { name: 'Asignaciones óptimas' }).textContent).toBe(original)
      expect(show).toHaveBeenCalledTimes(2)
    } finally {
      if (showDescriptor) Object.defineProperty(prototype, 'showModal', showDescriptor)
      else Reflect.deleteProperty(prototype, 'showModal')
      if (closeDescriptor) Object.defineProperty(prototype, 'close', closeDescriptor)
      else Reflect.deleteProperty(prototype, 'close')
      vi.unstubAllGlobals()
    }
  })
})
